def normalize_city_name(name: str) -> str:
    if not name:
        return ""
    s = name.strip().lower()
    s = s.replace("ё", "е")
    s = re.sub(r"\s+", " ", s)
    return s


def geocode(city_name: str) -> tuple[float, float] | None:
    if not city_name:
        return None
    key = normalize_city_name(city_name)
    return CITY_COORDS.get(key)
